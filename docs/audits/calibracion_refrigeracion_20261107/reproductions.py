"""Reproduce the 2023 cooling calibration of SPEC-016 (D-V6-16 to D-V6-19) on the 17 buildings.

Uses distill_building_loads.calibrate_building_physical on the iquitos_v5 train_2023 split without
writing any file, with CityLearn's heat-pump COP and the schema refrigerant target.

Run: .venv39-citylearn-v3/Scripts/python.exe docs/audits/calibracion_refrigeracion_20261107/reproductions.py
"""
import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT/'tools/dataset'))
sys.path.insert(0, str(ROOT))

import distill_building_loads as dl  # noqa: E402
from uc3m.application.dataset import hvac_capacity as hc  # noqa: E402

SPLIT = ROOT/'data/campaigns/iquitos_v5/splits/train_2023'

if __name__ == '__main__':
    dl.configure_building_types(yaml.safe_load((ROOT/'configs/dataset/building_types.yaml').read_text(encoding='utf-8')))
    norms = hc.load_hvac_norms(ROOT/'configs/dataset/hvac_norms.yaml')
    schema, weather = dl.load_schema(SPLIT), pd.read_csv(SPLIT/'weather.csv')
    for b in range(1, 18):
        try:
            r = dl.calibrate_building_physical(b, schema, weather, norms=norms, dataset_dir=SPLIT,
                                               measurements=dl._DEFAULT_MEASUREMENTS, write=False)
        except ValueError as error:  # B01 has no measured bill: B_01.csv is generated by the project
            print(f'B{b:02d} sin factura medida: {error}')
            continue
        rep = r.report
        bill = rep[['E_peak_medido_kWh', 'E_offpeak_medido_kWh']].to_numpy().sum()
        physical = rep[['E_peak_cooling_fisico_kWh', 'E_offpeak_cooling_fisico_kWh']].to_numpy().sum()
        cooling = rep[['E_peak_cooling_kWh', 'E_offpeak_cooling_kWh']].to_numpy().sum()
        print(f"B{b:02d} kWth={r.capacity.kw_thermal:6.0f} COPdis={r.design_cop:4.2f} kWe={r.nominal_power_kw:6.0f} "
              f"fisico/factura={physical/bill*100:6.1f}% refrig={cooling/bill*100:5.1f}% "
              f"meses_recortados={int(rep['capped'].sum()):2d}")
