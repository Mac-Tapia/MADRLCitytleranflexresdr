def main():
    parser = argparse.ArgumentParser(description="Build bibliographic matrix CSV")
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    all_papers = list(PAPERS)
    for i, (title, authors, year, source, doi, indexation, axis, desc) in enumerate(ADDITIONAL_PAPERS_TEMPLATE):
        n = len(PAPERS) + i + 1
        all_papers.append(make_additional_row(n, title, authors, year, source, doi, indexation, axis, desc))

    # Determinar columnas del primer paper
    fieldnames = list(all_papers[0].keys())

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)

    with open(out, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(all_papers)

    print(f"Matriz bibliografica generada: {out} ({len(all_papers)} papers)")
    print("Papers con datos completos verificados: 20")
    print("Papers con datos pendientes de verificacion: 30")


if __name__ == "__main__":
    main()
